// --- 3D position generator (Fibonacci sphere with depth variation) ---
function _pos(angle, dist, height, zOffset = 0) {
  const rad = (angle * Math.PI) / 180;
  return {
    x: Math.cos(rad) * dist,
    y: height,
    z: Math.sin(rad) * dist + zOffset
  };
}

